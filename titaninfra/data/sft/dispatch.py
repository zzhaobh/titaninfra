"""
Dispatch — the single runtime entrypoint for SFT tokenisation.

Every production callsite (``streaming_dataset.py``, ``sft_utils.py``,
recipe-level helpers) calls ``tokenize_sample(...)``. There is no mode
switch: one capability-check → normalize → router → encoder → encode
flow per sample.

Capability check (P0-1c, 2026-05-31): before normalize, dispatch
inspects the target family's ``SUPPORTED_BLOCKS`` set (declared at the
top of each ``encoders/<family>.py``) and structurally drops any block
whose type is not in that set, emitting one warning per skipped block
via ``capabilities.warn_unsupported_block``. The encoder then sees a
pruned sample and never has to defend against unsupported blocks.

If pruning empties out every assistant message, ``EmptyAssistantError``
is raised — the sample contributes no learnable content and emitting
a zero-loss EncodedSample would mask the misconfiguration. See
[[feedback_capability_mismatch_must_fail_loud]] for the warn-loud
contract.

Per-family behaviour lives in ``encoders/<family>.py`` (registered via
``@register("<family>")``) and is selected by ``router.route()``. To add
a new family, drop in a new encoder module; do not edit this file.

Antipattern (do not reintroduce): ms-swift carries a runtime dual
backend (``_swift_encode`` vs ``_jinja_encode``) chosen by a mode flag,
which forces every change to be implemented and validated twice and
hides divergence behind the flag. The per-family encoder registry is
the only extension point in titaninfra — do not reintroduce a mode
parameter to this module.

SFT vs RL split: dispatch is the **SFT-only** entrypoint. RL prompt
construction goes through ``assembler.assemble(mode='rl_prompt',
add_generation_prompt=True)`` directly — exposing the flag on this SFT
entrypoint is a footgun (any True call pollutes training data with an
unfinished assistant header) and is intentionally absent. The single
exception is ``gemma4``, whose encoder still routes through jinja-render
+ boundary scan and therefore appends the trailer inside its own
``encode``; that branch is internal to the encoder and never reachable
from this dispatch path.
"""

from __future__ import annotations

import copy
import importlib

from titaninfra.data.schema import (
    ImageBlock,
    TextBlock,
    ThinkingBlock,
    ToolResultBlock,
    ToolUseBlock,
)
from titaninfra.data.sft import normalize, router
from titaninfra.data.sft.capabilities import (
    FEATURE_IMAGE,
    FEATURE_LOSS_WEIGHT_PER_BLOCK,
    FEATURE_LOSS_WEIGHT_PER_MESSAGE,
    FEATURE_MULTI_TURN,
    FEATURE_PARALLEL_TOOL_CALLS,
    FEATURE_SYSTEM,
    FEATURE_THINKING_CURRENT_TURN,
    FEATURE_THINKING_HISTORY,
    FEATURE_THINKING_INTENT_EFFORT,
    FEATURE_THINKING_INTENT_MODE,
    FEATURE_TOOL_CALL,
    FEATURE_TOOL_RESULT,
    FEATURE_TOOLS_DECLARATION,
    FEATURE_TYPE_OVERRIDES,
    EmptyAssistantError,
    warn_unsupported_block,
    warn_unsupported_feature,
)
from titaninfra.data.sft.encoders import get_encoder
from titaninfra.data.sft.loss_policy import LossPolicy, resolve_weights
from titaninfra.data.sft.types import EncodedSample

# Map raw JSON type tags to schema Block classes for capability checks.
_BLOCK_TAG_TO_CLASS: dict[str, type] = {
    "text": TextBlock,
    "thinking": ThinkingBlock,
    "tool_use": ToolUseBlock,
    "tool_result": ToolResultBlock,
    "image": ImageBlock,
}


def _get_supported_blocks(family: str) -> frozenset[type] | None:
    """Return the target family encoder's ``SUPPORTED_BLOCKS`` set, or None.

    Lazily imports the encoder module so the registry side effects fire.
    Returns None when the encoder module does not declare the constant —
    in that case capability check is skipped (legacy encoder; treat as
    "supports everything" until it opts in).
    """
    try:
        module = importlib.import_module(f"titaninfra.data.sft.encoders.{family}")
    except ModuleNotFoundError:
        return None
    return getattr(module, "SUPPORTED_BLOCKS", None)


def _get_supported_features(family: str) -> frozenset[str] | None:
    """Return the target family encoder's ``SUPPORTED_FEATURES`` set, or None.

    Mirrors ``_get_supported_blocks``; legacy encoders without the
    declaration are treated as supports-everything and skip feature
    warnings. Adding the declaration is the migration path.
    """
    try:
        module = importlib.import_module(f"titaninfra.data.sft.encoders.{family}")
    except ModuleNotFoundError:
        return None
    return getattr(module, "SUPPORTED_FEATURES", None)


def _detect_features(sample_json: dict) -> frozenset[str]:
    """Inspect a (post-prune) sample and return the set of features it uses.

    Detection rules are intentionally syntactic — we read the same dict
    fields the encoder will read, not the normalized form. Running this
    AFTER block prune means we don't warn about features that were
    already structurally removed (e.g. no ``tool_call`` warning if every
    tool_use block was pruned because the family can't render it).

    Each feature corresponds to a ``FEATURE_*`` constant in
    ``capabilities.py``. Add new detection here when extending the IR.
    """
    features: set[str] = set()
    messages = sample_json.get("messages") or []
    tools = sample_json.get("tools")
    system = sample_json.get("system")
    loss_config = sample_json.get("loss_config") or {}
    thinking_intent = sample_json.get("thinking_intent")

    if system:
        features.add(FEATURE_SYSTEM)
    if isinstance(tools, list) and tools:
        features.add(FEATURE_TOOLS_DECLARATION)
    if isinstance(loss_config, dict) and loss_config.get("type_overrides"):
        features.add(FEATURE_TYPE_OVERRIDES)
    # thinking_intent is a top-level optional field on SFTSample. We split
    # detection across two sub-flags so the wire reality is honored: only
    # gpt_oss carries a wire-level `Reasoning: <effort>` field; qwen3 /
    # dsv4 / gemma4 templates have a mode-equivalent but no effort dial.
    # Per-sub-field detection lets each family declare exactly what it
    # implements, and the warn-loud surfaces e.g. `effort` set against
    # dsv4 as a precise capability gap. See
    # [[feedback_capability_mismatch_must_fail_loud]].
    if isinstance(thinking_intent, dict):
        if thinking_intent.get("mode") is not None:
            features.add(FEATURE_THINKING_INTENT_MODE)
        if thinking_intent.get("effort") is not None:
            features.add(FEATURE_THINKING_INTENT_EFFORT)
    elif thinking_intent is not None:
        # Already-decoded ``ThinkingIntent`` struct (msgspec). Attribute
        # access mirrors the dict path; ``None`` sub-fields are skipped.
        if getattr(thinking_intent, "mode", None) is not None:
            features.add(FEATURE_THINKING_INTENT_MODE)
        if getattr(thinking_intent, "effort", None) is not None:
            features.add(FEATURE_THINKING_INTENT_EFFORT)

    user_count = 0
    assistant_count = 0
    last_assistant_idx = -1
    for idx, msg in enumerate(messages):
        if not isinstance(msg, dict):
            continue
        role = msg.get("role")
        if role == "system":
            features.add(FEATURE_SYSTEM)
        elif role == "user":
            user_count += 1
        elif role == "assistant":
            assistant_count += 1
            last_assistant_idx = idx
        if isinstance(msg.get("weight"), (int, float)):
            features.add(FEATURE_LOSS_WEIGHT_PER_MESSAGE)

        blocks = msg.get("blocks")
        if not isinstance(blocks, list):
            continue
        for block in blocks:
            if not isinstance(block, dict):
                continue
            btag = block.get("type")
            if btag == "image":
                features.add(FEATURE_IMAGE)
            elif btag == "tool_result":
                features.add(FEATURE_TOOL_RESULT)
            if isinstance(block.get("weight"), (int, float)):
                features.add(FEATURE_LOSS_WEIGHT_PER_BLOCK)
        if role == "tool":
            features.add(FEATURE_TOOL_RESULT)

    if user_count >= 2 or assistant_count >= 2:
        features.add(FEATURE_MULTI_TURN)

    # Thinking / tool_use / parallel_tool_calls require knowing assistant
    # position (current vs history), so this is a second pass over
    # assistant messages only.
    for idx, msg in enumerate(messages):
        if not isinstance(msg, dict) or msg.get("role") != "assistant":
            continue
        # HF-standard ``tool_calls`` field on the message (not in blocks):
        # surface as FEATURE_TOOL_CALL too so capability dispatch warns
        # families that don't support tools (qwen2_5, llama3). Otherwise
        # the encoder silently emits an empty assistant body. (Phase 3.1)
        hf_tool_calls = msg.get("tool_calls")
        if isinstance(hf_tool_calls, list) and hf_tool_calls:
            features.add(FEATURE_TOOL_CALL)
            if len(hf_tool_calls) >= 2:
                features.add(FEATURE_PARALLEL_TOOL_CALLS)
        blocks = msg.get("blocks")
        if not isinstance(blocks, list):
            continue
        tool_use_count = 0
        for block in blocks:
            if not isinstance(block, dict):
                continue
            btag = block.get("type")
            if btag == "thinking":
                if idx == last_assistant_idx:
                    features.add(FEATURE_THINKING_CURRENT_TURN)
                else:
                    features.add(FEATURE_THINKING_HISTORY)
            elif btag == "tool_use":
                features.add(FEATURE_TOOL_CALL)
                tool_use_count += 1
        if tool_use_count >= 2:
            features.add(FEATURE_PARALLEL_TOOL_CALLS)

    return frozenset(features)


def _warn_unsupported_features(
    used: frozenset[str],
    supported: frozenset[str],
    family: str,
) -> None:
    """Log one warning per (sample, feature) the family does not implement.

    Unlike block prune this is purely advisory — the encoder still runs
    and emits tokens. The warning surfaces semantic drift (e.g. a
    ``loss_weight_per_block`` sample sent to qwen2_5 will lose its
    per-token weighting silently because the family encoder ignores
    the field). Sorted for deterministic log ordering across runs.
    """
    for feature in sorted(used - supported):
        warn_unsupported_feature(
            family=family,
            feature=feature,
            reason=f"not in {family}.SUPPORTED_FEATURES",
        )


def _prune_unsupported_blocks(
    sample_json: dict,
    supported: frozenset[type],
    family: str,
) -> tuple[dict, list[str], int]:
    """Deep-copy ``sample_json`` and drop blocks whose type is not supported.

    Returns a 3-tuple:
    * ``pruned``        — deepcopy of input with unsupported blocks removed.
    * ``skipped``       — flat list of skipped block type names (forensics).
    * ``emptied_assistants`` — count of assistant messages whose blocks
      list went fully empty due to pruning. Drives EMPTY-RAISE: a sample
      whose only assistant content was unsupported blocks now has zero
      learnable signal, even if the empty-shell messages were dropped in
      the second pass.

    Two passes:
    1. Per-block prune (warn-loud on each skip).
    2. Drop messages whose ``blocks`` is now empty AND who have no
       fallback string ``content``. Reason: a tool-role message
       stripped of its only ToolResultBlock has no semantic content
       for the encoder; leaving the shell makes the encoder's
       role-based dispatch fire on a meaningless turn. The
       ``emptied_assistants`` counter is captured BEFORE this drop so
       EMPTY-RAISE can still see what was lost.

    The original input dict is not mutated.
    """
    pruned = copy.deepcopy(sample_json)
    skipped: list[str] = []
    messages = pruned.get("messages") or []
    for msg_idx, msg in enumerate(messages):
        if not isinstance(msg, dict):
            continue
        blocks = msg.get("blocks")
        if not isinstance(blocks, list):
            # ``content`` (string) path: nothing to prune at block level.
            continue
        kept: list = []
        for blk_idx, block in enumerate(blocks):
            if not isinstance(block, dict):
                kept.append(block)
                continue
            tag = block.get("type")
            cls = _BLOCK_TAG_TO_CLASS.get(tag)
            if cls is None:
                # Unknown tag — keep as-is and let normalize/encoder fail
                # the loud way; this is a schema error not a capability
                # mismatch.
                kept.append(block)
                continue
            if cls in supported:
                kept.append(block)
            else:
                warn_unsupported_block(
                    family=family,
                    block_type_name=cls.__name__,
                    message_index=msg_idx,
                    block_index=blk_idx,
                    reason=f"not in {family}.SUPPORTED_BLOCKS",
                )
                skipped.append(cls.__name__)
        msg["blocks"] = kept

    # Count assistant messages whose blocks went empty BEFORE we drop
    # them in the second pass — needed for EMPTY-RAISE forensics.
    emptied_assistants = sum(
        1 for m in messages
        if isinstance(m, dict)
        and m.get("role") == "assistant"
        and isinstance(m.get("blocks"), list)
        and len(m["blocks"]) == 0
        and not (isinstance(m.get("content"), str) and m["content"])
    )

    # Second pass: drop messages whose blocks list went empty AND who
    # carry no fallback string ``content``.
    pruned["messages"] = [
        m for m in messages
        if not (
            isinstance(m, dict)
            and isinstance(m.get("blocks"), list)
            and len(m["blocks"]) == 0
            and not (isinstance(m.get("content"), str) and m["content"])
        )
    ]
    return pruned, skipped, emptied_assistants


def _has_no_assistant_content(sample_json: dict) -> bool:
    """True iff every assistant message in the pruned sample has no content.

    Considers both ``blocks`` (post-prune) and ``content`` (string-path
    fallback). If no assistant messages remain (because the prune drop
    pass removed them), returns True — the caller already captured the
    ``emptied_assistants`` count from prune and treats no-remaining-
    assistant as a downstream signal that EMPTY-RAISE applies.
    """
    assistants = [
        m for m in (sample_json.get("messages") or [])
        if isinstance(m, dict) and m.get("role") == "assistant"
    ]
    if not assistants:
        return True
    for m in assistants:
        blocks = m.get("blocks")
        content = m.get("content")
        if isinstance(blocks, list) and blocks:
            return False
        if isinstance(content, str) and content:
            return False
    return True


def _resolve_history_policy(family: str, user_policy):
    """Resolve history policy."""
    if user_policy is None:
        return None
    return user_policy


def tokenize_sample(
    sample_json: dict,
    tokenizer,
    family: str,
    *,
    max_length: int | None = None,
    loss_config: dict | None = None,
    truncate_at_last_segment: bool = False,
    sft_mask_mode: str = "auto",
    train_on_inputs: bool = False,
    history_policy=None,
    resolution_policy=None,
    spatial_merge_size: int | None = None,
    decoded_images: list | None = None,
) -> EncodedSample:
    """Tokenise one raw SFT sample to an ``EncodedSample``.

    Flow: capability_check → normalize → router → get_encoder → encode.

    Capability check is two-stage warn-loud:

    * **Block-level (structural prune)** — blocks whose type is not in
      ``encoders.<family>.SUPPORTED_BLOCKS`` are logged via
      ``warn_unsupported_block`` and dropped. If pruning empties every
      assistant message, raises ``EmptyAssistantError``.
    * **Feature-level (advisory warning)** — features detected on the
      post-prune sample but absent from
      ``encoders.<family>.SUPPORTED_FEATURES`` are logged via
      ``warn_unsupported_feature``. The encoder still runs; this
      surfaces semantic drift where the encoder will silently ignore
      something the data carried (e.g. per-block ``weight`` sent to a
      family with no per-block loss support).

    Encoders without ``SUPPORTED_*`` declarations (legacy) are treated
    as "supports everything" and skip the corresponding check. Adding
    the declaration to such an encoder is the migration path.

    See [[feedback_capability_mismatch_must_fail_loud]] for the contract.

    Boundary builder (``sft_mask_mode`` / ``train_on_inputs``)
    ---------------------------------------------------------
    After normalize and before encode, ``LossPolicy.resolve_weights``
    collapses the training-side masking policy into each
    ``NormalizedMessage.weight`` (the encoder reads only that weight; it
    never sees the policy — see ``encoders/base.py`` "boundary builder
    (upstream)"). This is the single place ``StreamConfig.sft_mask_mode``
    takes effect:

    * ``"auto"`` (default) — assistant turns get weight 1.0, everything
      else 0.0, but an explicit per-message ``weight==0`` is always
      respected (silencing carve-out). NOTE this OVERRIDES a non-zero
      custom assistant weight back to 1.0 (auto = binary assistant-only
      loss); use ``"manual"`` to honor continuous per-message weights.
    * ``"manual"`` — pass each normalized per-message weight through
      verbatim (per-message / per-block ``weight`` annotations win).
    * ``train_on_inputs=True`` — Layer 1 override: every message weight
      becomes 1.0 (prompt included). ``StreamConfig`` has no such field
      yet; only ``sft_utils.encode_messages`` sets it.

    ``type_overrides`` (per-block dial, e.g. ``{"thinking": 0.3}``) is
    carried on the policy for the encoder to consume when emitting
    THINKING / TOOL_CALL segments; ``resolve_weights`` does not apply it
    to message-level weights.
    """
    supported = _get_supported_blocks(family)
    if supported is not None:
        sample_json, skipped, _emptied_assistants = _prune_unsupported_blocks(
            sample_json, supported, family,
        )
        # EMPTY-RAISE fires only when the post-prune sample has no
        # remaining assistant content of any form (every assistant
        # message went empty, or none remain after the drop pass).
        # A single emptied turn in a multi-turn sample is NOT enough —
        # other assistant turns may still carry learnable content.
        if skipped and _has_no_assistant_content(sample_json):
            raise EmptyAssistantError(
                family=family,
                skipped_block_types=skipped,
                sample_repr=f"messages={len(sample_json.get('messages') or [])}",
            )

    # Feature warn-loud (advisory, never raises). Runs AFTER block
    # prune so we don't warn about features the prune already removed.
    supported_features = _get_supported_features(family)
    if supported_features is not None:
        used_features = _detect_features(sample_json)
        _warn_unsupported_features(used_features, supported_features, family)

    _eff_hp = _resolve_history_policy(family, history_policy)
    if _eff_hp is not None:
        sample_json = {**sample_json, "history_policy": _eff_hp}
    normalized = normalize.from_sft_sample(sample_json)

    # Boundary builder: collapse (sft_mask_mode × train_on_inputs ×
    # per-message weight) into NormalizedMessage.weight so the encoder
    # reads a single finalized weight. type_overrides stays on loss_config
    # (the encoder applies it per-block); LossPolicy only carries it.
    _type_overrides = loss_config.get("type_overrides") if isinstance(loss_config, dict) else None
    normalized = resolve_weights(
        normalized,
        LossPolicy(
            sft_mask_mode=sft_mask_mode,
            train_on_inputs=train_on_inputs,
            type_overrides=_type_overrides,
        ),
    )

    encoder_name = router.route(normalized, family)
    enc = get_encoder(encoder_name, tokenizer)
    _extra = {}
    if spatial_merge_size is not None:
        _extra["spatial_merge_size"] = spatial_merge_size
    if decoded_images is not None:
        _extra["decoded_images"] = decoded_images
    return enc.encode(
        normalized,
        max_length=max_length,
        loss_config=loss_config,
        truncate_at_last_segment=truncate_at_last_segment,
        **_extra,
    )


